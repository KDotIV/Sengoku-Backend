using System.Collections.Concurrent;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using System.Text.Json;
using System.Reflection;

namespace Sengoku.Observability;

/// <summary>Explicit scalar allowlist. Unknown fields and objects are never serialized.</summary>
public sealed class OperationDataPolicy
{
    private sealed record Field(string Name, Func<object, string?> Format);
    private readonly ConcurrentDictionary<string, Field> fields = new(StringComparer.OrdinalIgnoreCase);
    private static readonly Regex Sensitive = new("password|passwd|pwd|secret|token|hash|apikey|authorization|authheader|bearer|cookie|credential|connectionstring|email|address|payload|body|sql|query|url", RegexOptions.IgnoreCase | RegexOptions.Compiled);
    private static readonly Regex Code = new("^[a-zA-Z0-9_.:-]{1,160}$", RegexOptions.Compiled);

    public OperationDataPolicy()
    {
        foreach (var name in new[] { "UserId", "PlayerId", "EventId", "EventLinkId", "TournamentId", "TournamentLink", "TournamentLinkId", "LeagueId", "GameId", "GuildId", "ChannelId", "SubscriptionId", "FeedId", "RegionId", "WorkflowId", "MessageId", "DeliveryCount", "Attempt", "RowsAffected", "ItemCount", "ResultCount", "Page", "StageCount", "ErrorCount", "HttpStatusCode", "EventCode", "SessionFingerprint", "Outcome", "ReasonCode", "Settlement", "Category", "ErrorType", "ErrorSite", "Dependency", "StateCode", "Topic" })
            fields[name] = new(name, Scalar);
        foreach (var name in new[] { "SessionActive", "SessionCreated", "SessionRevoked", "Created", "Committed", "Result", "HasResult", "Retryable" })
            fields[name] = new(name, value => value is bool flag ? flag.ToString().ToLowerInvariant() : null);
        fields["Username"] = new("Username", value => value is string s ? s : null);
    }

    /// <summary>Review each new field's privacy and meaning before registering a scalar formatter.</summary>
    public void Allow(string name, Func<object, string?> formatter)
    {
        if (!Code.IsMatch(name) || IsSensitive(name)) throw new ArgumentException("Sensitive or invalid telemetry field.", nameof(name));
        fields[name] = new(name, formatter);
    }

    public Dictionary<string, string> Sanitize(IEnumerable<KeyValuePair<string, object?>>? values)
    {
        var result = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        if (values == null) return result;
        foreach (var pair in values.Take(24))
        {
            if (pair.Value == null || !fields.TryGetValue(pair.Key, out var field)) continue;
            // The only credential-derived field is generated by SessionFingerprint below.
            if (IsSensitive(pair.Key)) continue;
            try
            {
                var value = field.Format(pair.Value);
                if (value != null)
                {
                    result[field.Name] = Clean(value, 100);
                    if (value.Length > 100) result["MetadataTruncated"] = "true";
                    if (Encoding.UTF8.GetByteCount(JsonSerializer.Serialize(result)) > 2000)
                    {
                        result.Remove(field.Name);
                        result["MetadataTruncated"] = "true";
                    }
                }
            }
            catch { /* A metadata formatter must never break business work. */ }
        }
        return result;
    }
    internal Dictionary<string, string> Project(object? value)
    {
        if (value == null || value.GetType().Namespace?.StartsWith("Sengoku", StringComparison.Ordinal) != true) return new();
        // Read reviewed scalar properties only, never enumerate an object graph or invoke serializers on DTOs.
        var projected = new List<KeyValuePair<string, object?>>();
        foreach (var property in value.GetType().GetProperties(BindingFlags.Instance | BindingFlags.Public))
        {
            if (!fields.ContainsKey(property.Name) || IsSensitive(property.Name) || property.GetIndexParameters().Length != 0) continue;
            try { projected.Add(new(property.Name, property.GetValue(value))); } catch { }
        }
        return Sanitize(projected);
    }

    internal static string Label(string text) => Code.IsMatch(text) ? text : "Unspecified";
    private static bool IsSensitive(string name) => Sensitive.IsMatch(new string(name.Where(char.IsLetterOrDigit).ToArray()));
    internal static void Merge(Dictionary<string, string> target, Dictionary<string, string> source)
    {
        foreach (var pair in source)
        {
            var hadPrevious = target.TryGetValue(pair.Key, out var previous);
            target[pair.Key] = pair.Value;
            if (target.Count > 24 || Encoding.UTF8.GetByteCount(JsonSerializer.Serialize(target)) > 2000)
            {
                if (hadPrevious) target[pair.Key] = previous!;
                else target.Remove(pair.Key);
                target["MetadataTruncated"] = "true";
            }
        }
    }
    private static string? Scalar(object value) => value switch
    {
        string s when Code.IsMatch(s) => s,
        Guid g => g.ToString("D"),
        bool b => b.ToString().ToLowerInvariant(),
        byte or short or int or long or uint or ulong or decimal or double or float => Convert.ToString(value, CultureInfo.InvariantCulture),
        Enum e => e.ToString(),
        _ => null
    };
    private static string Clean(string value, int limit) => new(value.Where(c => !char.IsControl(c)).Take(limit).ToArray());

    // Different from the database token hash; never export the database credential verifier.
    public static string? SessionFingerprint(string? token) => token is { Length: 64 } && token.All(Uri.IsHexDigit)
        ? Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes("Sengoku.Telemetry.Session.v1:" + token)))
        : null;
}

public static class OperationFields
{
    public static Dictionary<string, object?> Of(params (string Name, object? Value)[] fields) => fields.ToDictionary(f => f.Name, f => f.Value);
}
